const NAMES = { fin: 'כספים ותזרים', sup: 'ספקים ורכש', emp: 'עובדים', cus: 'לקוחות ומכירות', mgt: 'ניהול וזמן' };

// הנחיה לפי הנושא: רק התחומים שמופיעים בשאלה (ואם אף אחד – תקציר של כולם, שורה לתחום)
function guideFor(text) {
  const s = String(text || '');
  const hit = Object.keys(TOPIC).filter((k) => TOPIC[k].test(s));
  const keys = hit.length ? hit : Object.keys(TOPIC);
  const lines = [];
  for (const k of keys) {
    lines.push('• ' + NAMES[k] + ':');
    for (const m of M.filter((x) => x[1] === k)) {
      lines.push('  - ' + m[2] + (m[3] ? ' (יש באפליקציה: ' + m[3] + ')' : ' (אין באפליקציה)') + (m[4] ? ' | אם חסר נתון – לשאול: "' + m[4] + '"' : ''));
    }
  }
  return { topics: keys, text: lines.join('\n') };
}

